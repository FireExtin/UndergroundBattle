import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {frozenAbi88,stageFrozenAbi88} from './frozen-kernels.mjs';
import {loadFixture,assertSources,compare,sha256} from './xq23-oracle.mjs';
import {loadP2Fixture,compareP2} from './xq23-p2-oracle.mjs';
import {kernel,moduleBytes} from '../rust-game-wasm/tests/current88-kernel.mjs';
test('v70 ABI88 preserves original139 compiler inputs, complete XQ23 and both actual P2 witnesses',()=>{
 const saved=frozenAbi88(),f=loadFixture(),p2=loadP2Fixture();
 assert.equal(saved.identity.providerSource,'8061ec2cb987202e68b9a4dd15ff57730364ee03');
 assert.equal(sha256(saved.wasm),'5834f38dcdb9952a2430e7eb08c44ee9c4a1c98bc4a8ab138c4aee3c343ccde3');
 assert.equal(saved.wasm.length,3353559);assert.equal(Object.keys(f.sourceBindings.files).length,139);
 assert.equal(sha256(readFileSync(new URL('../rust-game-wasm/tests/xq23Native88.fixture.json.gz',import.meta.url))),saved.identity.nativeFixtureSha256);
 assert.equal(sha256(readFileSync(new URL('../rust-game-wasm/tests/xq23P2Native88.fixture.json.gz',import.meta.url))),saved.identity.p2NativeFixtureSha256);
 assert.deepEqual(f.counts,{scenarios:9,commands:72,rejected:5,projections:324,invalidRestores:31});
 assert.equal(compare(f,kernel,moduleBytes).completeOpaqueStatesJournalsAndFourViews,true);
 assert.equal(compareP2(p2,kernel,moduleBytes).opaqueTransitionsJournalsAndFourViewsEqual,true);
 const changed=structuredClone(f.sourceBindings);changed.files['rust-game/src/engine.rs']='0'.repeat(64);
 assert.throws(()=>assertSources(changed),/Exact original Native88 compiler binding/);
 const dest=mkdtempSync(path.join(tmpdir(),'frozen88-stage-'));stageFrozenAbi88(dest);
 assert.deepEqual(readdirSync(dest).sort(),['hegemony_wasm.js','hegemony_wasm_bg.wasm']);
 assert.deepEqual(readFileSync(path.join(dest,'hegemony_wasm_bg.wasm')),saved.wasm);
});
test('missing or corrupt v70 runtime is preserved and rejected without rebuilding an old core',()=>{
 const saved=frozenAbi88(),empty=mkdtempSync(path.join(tmpdir(),'frozen88-missing-'));
 assert.throws(()=>frozenAbi88({directory:empty}),/Missing published ABI88/);
 writeFileSync(path.join(empty,'hegemony_wasm.js'),saved.js);writeFileSync(path.join(empty,'hegemony_wasm_bg.wasm.gz'),'corrupt');
 assert.throws(()=>frozenAbi88({directory:empty}),/ABI88 runtime hash mismatch/);
 assert.equal(readFileSync(path.join(empty,'hegemony_wasm_bg.wasm.gz'),'utf8'),'corrupt');
});
