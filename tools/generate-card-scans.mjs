// Expose only the admitted pool's original, unmodified scans for public reading.
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const pool = JSON.parse(readFileSync(path.join(root, 'rust-game/data/cards.json'), 'utf8'));
// Art only for the one reviewed real society, outside the ordinary-card registry.
// Synthetic fixture societies must never acquire public art or pool admission.
const societyScans = [{ id: 'MSJC09', source: {
  image: 'resource/ymsj-fun.github.io/cards/MSJC09 秘社.jpg',
  sha256: '41e478a3f38ead83477498fd88131831a5fd843be364c1c0daa3ba10153c2302',
} }];
const scans = {};
const out = path.join(root, 'web/public/cards');
mkdirSync(out, { recursive: true });
for (const card of [...pool.cards, ...societyScans]) {
  const relative = card.source?.image || card.source?.file;
  if (!/^[A-Z0-9]+$/.test(card.id) || !relative?.endsWith('.jpg')) throw new Error('Admitted card needs an original scan');
  const source = path.resolve(root, relative);
  if (!source.startsWith(path.join(root, 'resource') + path.sep)) throw new Error('Scan must stay in the provided source archive');
  const bytes = readFileSync(source);
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  if (card.source.sha256 && card.source.sha256 !== sha256) throw new Error('Original scan evidence hash differs');
  copyFileSync(source, path.join(out, card.id + '.jpg'));
  scans[card.id] = { url: '/cards/' + card.id + '.jpg', source: relative, sha256 };
}
writeFileSync(path.join(root, 'web/public/card-scans.json'), JSON.stringify(scans, null, 2) + '\n');
writeFileSync(path.join(root, 'web/src/game/cardScans.ts'), '// Generated by tools/generate-card-scans.mjs from the admitted pool. Artwork is not a rules registry.\nconst scans: Record<string, string> = ' + JSON.stringify(Object.fromEntries(Object.entries(scans).map(([id, scan]) => [id, scan.url])), null, 2) + ';\nexport const cardScanUrl = (cardId?: string) => cardId ? scans[cardId] : undefined;\n');
console.log(JSON.stringify({ scans: Object.keys(scans).length, unchangedOriginalBytes: true }));
